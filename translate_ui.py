#!/usr/bin/env python3
"""
Extract all t('...') keys from Dart files, translate them to Amharic
via MyMemory (free, no API key), and write them into lib/utils/translations.dart.
"""

import os, re, sys, glob, json, urllib.request, urllib.parse, time

MYMEMORY_URL = 'https://api.mymemory.translated.net/get'
TARGET_LOCALE = 'am'
TRANSLATIONS_FILE = 'lib/utils/translations.dart'

def extract_keys_from_dart_files(root_dir):
    """Scan all .dart files for t('...') or t("..."), skip keys containing '$'."""
    keys = set()
    pat1 = re.compile(r"\bt\('((?:[^'\\]|\\.)*)'\)")
    pat2 = re.compile(r'\bt\("((?:[^"\\]|\\.)*)"\)')
    for fp in glob.glob(os.path.join(root_dir, 'lib/**/*.dart'), recursive=True):
        if 'translations.dart' in fp:
            continue
        with open(fp, 'r', encoding='utf-8') as f:
            content = f.read()
        for m in pat1.finditer(content):
            key = m.group(1).replace("\\'", "'")
            if '$' not in key:
                keys.add(key)
        for m in pat2.finditer(content):
            key = m.group(1).replace('\\"', '"')
            if '$' not in key:
                keys.add(key)
    return sorted(keys)

def translate_via_mymemory(text, target):
    lang_pair = f'en|{target}'
    params = urllib.parse.urlencode({'q': text, 'langpair': lang_pair})
    url = f'{MYMEMORY_URL}?{params}'
    try:
        with urllib.request.urlopen(url, timeout=15) as resp:
            data = json.loads(resp.read().decode())
        if data.get('responseStatus') == 200:
            translated = data.get('responseData', {}).get('translatedText', '')
            if translated and translated.strip():
                return translated
        print(f"  MyMemory empty or error for '{text}'")
    except Exception as e:
        print(f"  Failed to translate '{text}': {e}")
    return None

def write_translations_file(translations, path):
    with open(path, 'w', encoding='utf-8') as f:
        f.write('// AUTO‑GENERATED by translate_ui.py\n')
        f.write("import '../core/app_config.dart';\n\n")
        f.write('const Map<String, String> amTranslations = {\n')
        for eng, amh in sorted(translations.items()):
            escaped_eng = eng.replace('\\', '\\\\').replace("'", "\\'")
            escaped_amh = amh.replace('\\', '\\\\').replace("'", "\\'")
            f.write(f"  '{escaped_eng}': '{escaped_amh}',\n")
        f.write('};\n\n')
        f.write('String t(String english) {\n')
        f.write('  if (AppConfig.isAmharic.value) {\n')
        f.write('    return amTranslations[english] ?? english;\n')
        f.write('  }\n')
        f.write('  return english;\n')
        f.write('}\n')

if __name__ == '__main__':
    root = os.path.abspath(os.path.dirname(__file__))
    print("Scanning Dart files for t('...') calls...")
    all_keys = extract_keys_from_dart_files(root)
    print(f"Found {len(all_keys)} unique static keys.")

    if not all_keys:
        print("No keys found. Exiting.")
        sys.exit(0)

    translations = {}
    for key in all_keys:
        print(f"Translating: {key}")
        amh = translate_via_mymemory(key, TARGET_LOCALE)
        if amh:
            translations[key] = amh
        else:
            translations[key] = f"[am] {key}"   # fallback placeholder
        time.sleep(0.2)   # be gentle to the free API

    write_translations_file(translations, os.path.join(root, TRANSLATIONS_FILE))
    print("Done! Rebuild the app to see real Amharic.")